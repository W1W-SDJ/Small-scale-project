// Generate the packed hit-test mask the renderer uses for click-through.
//
//   node tools/mask.mjs [pet.png] [sprite-mask.js]
//
// One bit per pixel: set where the sprite is opaque enough to be worth
// catching the mouse. Packed and base64-encoded into a plain <script> so the
// renderer can decode it with atob() — no fetch (blocked on file://) and no
// canvas (tainted by file:// images).
import { readFileSync, writeFileSync } from 'node:fs'
import { PNG } from 'pngjs'

const src = process.argv[2] ?? 'assets/pet.png'
const out = process.argv[3] ?? 'assets/sprite-mask.js'
const THRESHOLD = Number(process.env.MASK_THRESHOLD ?? 24)

const png = PNG.sync.read(readFileSync(src))
const count = png.width * png.height
const bytes = Buffer.alloc(Math.ceil(count / 8))
let solid = 0

for (let p = 0; p < count; p++) {
  if (png.data[p * 4 + 3] >= THRESHOLD) {
    bytes[p >> 3] |= 1 << (7 - (p & 7))
    solid++
  }
}

const js = `// Generated by tools/mask.mjs from ${src} — do not edit by hand.
window.__PET_MASK = { width: ${png.width}, height: ${png.height}, threshold: ${THRESHOLD}, data: "${bytes.toString('base64')}" }
`
writeFileSync(out, js)
console.log(`${src} ${png.width}x${png.height} -> ${out}`)
console.log(`solid pixels ${solid} (${((solid / count) * 100).toFixed(1)}%), alpha >= ${THRESHOLD}`)
